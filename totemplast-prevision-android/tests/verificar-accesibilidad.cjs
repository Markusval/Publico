/* Pruebas para ajustes de accesibilidad v1.4. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const A = require('../app/src/main/assets/accesibilidad.js');
const assets = path.resolve(__dirname, '../app/src/main/assets');
const html = fs.readFileSync(path.join(assets,'index.html'),'utf8');
const css = fs.readFileSync(path.join(assets,'styles.css'),'utf8');
const java = fs.readFileSync(path.resolve(__dirname,'../app/src/main/java/com/totemplast/prevision/MainActivity.java'),'utf8');
assert.deepEqual(A.normalize(null),{size:20,bold:true});
assert.deepEqual(A.normalize({size:22,bold:false}),{size:22,bold:false});
assert.deepEqual(A.normalize({size:26,bold:true}),{size:26,bold:true});
assert.deepEqual(A.normalize({size:-10,bold:"no"}),{size:20,bold:true});
assert.deepEqual(A.normalize({size:'24',bold:false}),{size:24,bold:false});
assert.deepEqual(A.SIZES,[18,20,22,24,26]);
const calls={};
const root={style:{setProperty:(key,value)=>calls[key]=value}};
A.apply(root,undefined);
assert.equal(calls['--totemplast-data-size'],'20px');
assert.equal(calls['--totemplast-data-weight'],'750');
A.apply(root,{size:26,bold:false});
assert.equal(calls['--totemplast-data-size'],'26px');
assert.equal(calls['--totemplast-data-weight'],'400');
for(const id of ['accessibilityPanel','dataFontSize','dataFontBold','resetAccessibility'])assert(html.includes('id="'+id+'"'), 'Falta '+id);
assert(html.includes('restoreAccessibilityPreferences();'));
assert(html.includes('setAccessibilityPreferences('));
assert(html.includes('localStorage.setItem(ACCESSIBILITY_KEY'));
assert(html.includes('<script src="accesibilidad.js"></script>'));
assert(css.includes('main .field input,main .saved-flex select,main .field select.rate-unit'));
assert(css.includes('font-size:var(--totemplast-data-size)'));
assert(css.includes('font-weight:var(--totemplast-data-weight)'));
assert(css.includes('main .field input::placeholder'));
assert(java.includes('"accesibilidad.js"'));
const inlineScripts=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)];
assert.equal(inlineScripts.length,1);
new vm.Script(inlineScripts[0][1],{filename:'index.html'});
console.log('v1.4: preferencias, tamaños, negrita, recuperación y sintaxis correctas.');
